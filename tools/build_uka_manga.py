if __name__ == "__main__":
    root = sys.argv[1] if len(sys.argv) > 1 else "ep_out"
    stat = {"実景": 0, "効果": 0, "白": 0}
    EFFECT = {"BG086", "BG087", "BG088", "BG089", "BG090", "BG091", "BG092",
              "BG093", "BG094", "BG096", "BG097", "BG098", "BG099", "BG100"}
    for ep, (title, pages) in EP.items():
        d = os.path.join(root, f"ep{ep}")
        os.makedirs(d, exist_ok=True)
        for i, (layout, panels) in enumerate(pages, 1):
            json.dump({"layout_id": layout, "title": title, "panels": panels},
                      open(os.path.join(d, f"p{i:02d}.json"), "w"),
                      ensure_ascii=False, indent=1)
            for p in panels:
                b = p.get("background_id")
                stat["白" if not b else ("効果" if b in EFFECT else "実景")] += 1
        print(f"第{ep}話「{title}」 {len(pages)}ページ")
    tot = sum(stat.values())
    print("背景の配分:", ", ".join(f"{k} {v}コマ({v/tot:.0%})" for k, v in stat.items()), f"/ 全{tot}コマ")
