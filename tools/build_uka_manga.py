import json, os, sys


def P(pose=None, bg=None, s=None, sfx=None, x=0.5, chars=None, scale=None, flip=False):
    d = {}
    if chars:
        d["chars"] = chars
    elif pose:
        d["pose_id"] = pose
        d["pose_x"] = x
        if scale:
            d["pose_scale"] = scale
    if bg:
        d["background_id"] = bg
    if s:
        d["serif"] = s
    if sfx:
        d["sfx"] = [{"text": t, "intensity": i} for t, i in sfx]
    return d


def N(t):          # ナレーション/モノローグ(角丸)
    return {"t": t, "shape": "角丸"}


def SH(t):         # 叫び
    return {"t": t, "shape": "叫び"}


def TG(t):         # トゲ(鋭い声)
    return {"t": t, "shape": "トゲ"}


def FU(t):         # 震え(弱い声)
    return {"t": t, "shape": "震え"}


def HI(t):         # ひそひそ
    return {"t": t, "shape": "ひそひそ"}


def C(pose, x, scale=1.0, flip=False):
    d = {"pose_id": pose, "x": x, "scale": scale}
    if flip:
        d["flip"] = True
    return d


